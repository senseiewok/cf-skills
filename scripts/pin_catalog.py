#!/usr/bin/env python3
"""Pin a snapshot of the research repository's source catalog for cf-skills.

The evidence skill (.claude/skills/cf-evidence-loop) ships with a generated copy of
sources/catalog.yaml from senseiewok/cf-research so that the skill works standalone
without requiring sibling checkouts or network.

This tool pins that copy to a specific research repository commit, recording:
  - the commit sha and commit date
  - the SHA-256 hash of the canonical sources/catalog.yaml at that commit (LF line endings)
  - the SHA-256 hash of the generated catalog copy (.claude/skills/cf-evidence-loop/catalog.yaml)
  - the source count and pin date

Usage:
  python scripts/pin_catalog.py [--source ../cf-research] [--ref <commit>] [--date YYYY-MM-DD] [--allow-old]
      Pin the catalog copy to the specified research commit (default: origin/main).
      Updates .claude/skills/cf-evidence-loop/catalog.yaml and .claude/skills/cf-evidence-loop/catalog.lock.json.

  python scripts/pin_catalog.py --status [--source ../cf-research]
      Report how far behind the pinned commit is relative to origin/main of the research repository.
      Exit 0 for any count; exit 2 on git failure or invalid lock.

  python scripts/pin_catalog.py --check [--source ../cf-research]
  python scripts/pin_catalog.py --verify [--source ../cf-research]
      Verify that catalog.yaml matches the PINNED commit (not main), and matches catalog.lock.json.
      Exit 0 when in sync; exit 1 on drift or modification.
      When run standalone (research repo missing), verifies catalog.yaml matches catalog.lock.json copy_sha256.
"""

from __future__ import annotations

import argparse
import datetime
import hashlib
import json
import os
from pathlib import Path
import re
import subprocess
import sys
from typing import Any, Callable, Sequence

ROOT = Path(__file__).resolve().parents[1]
SKILL_DIR = ROOT / ".claude" / "skills" / "cf-evidence-loop"
CATALOG_PATH = SKILL_DIR / "catalog.yaml"
LOCK_PATH = SKILL_DIR / "catalog.lock.json"

def resolve_default_source(root: Path = ROOT) -> Path:
    """Locate sibling cf-research whether running in main checkout or .worktrees/<repo>/<topic>."""
    sibling = root.parent / "cf-research"
    if sibling.exists() or len(root.parents) < 3:
        return sibling
    if root.parents[1].name == ".worktrees":
        wt_sibling = root.parents[2] / "cf-research"
        if wt_sibling.exists():
            return wt_sibling
    return sibling


DEFAULT_SOURCE = resolve_default_source(ROOT)
CATALOG_RESEARCH_PATH = "sources/catalog.yaml"
SCHEMA_VERSION = 1

COMMIT_RE = re.compile(r"^[0-9a-f]{40}$")
DATE_RE = re.compile(r"^[0-9]{4}-[0-9]{2}-[0-9]{2}$")

ALLOWED_ORIGINS = {
    "https://github.com/senseiewok/cf-research",
    "https://github.com/senseiewok/cf-research.git",
    "git@github.com:senseiewok/cf-research",
    "git@github.com:senseiewok/cf-research.git",
}

HEADER = (
    "# GENERATED from the lab's canonical catalog by pin_catalog.py.\n"
    "# Do not edit this file. Edit the canonical catalog in cf-research, run the pin tool, and commit both.\n"
    "# A drift check (--check) fails when this file and the pinned catalog differ.\n"
)

LEGACY_HEADER = (
    "# GENERATED from the lab's canonical catalog by sync_skill_catalog.py.\n"
    "# Do not edit this file. Edit the canonical catalog, run the sync tool, and commit both.\n"
    "# A drift check (--check) fails when this file and the canonical catalog differ.\n"
)


class Refused(Exception):
    """Raised when an operation is rejected by policy or validation."""


def lf_sha256(data: bytes) -> str:
    """SHA-256 of data with CRLF normalised to LF."""
    norm = data.replace(b"\r\n", b"\n")
    return hashlib.sha256(norm).hexdigest()


def strip_header(text: str) -> str:
    """Remove any generated header and the blank line following it."""
    for hdr in (HEADER, LEGACY_HEADER):
        if text.startswith(hdr):
            stripped = text[len(hdr):]
            return stripped[1:] if stripped.startswith("\n") else stripped
    return text


def count_sources(text: str) -> int:
    """Count sources from '  - id:' entries without requiring PyYAML."""
    matches = re.findall(r"^  - id:\s*(\S+)", text, re.M)
    count = len(matches)
    if count == 0:
        raise Refused("catalog has no '  - id:' entries")
    return count


def default_run(args: Sequence[str]) -> subprocess.CompletedProcess[bytes]:
    return subprocess.run(args, capture_output=True)


def git(run: Callable[[Sequence[str]], Any], source: Path | str, *args: str) -> bytes:
    """Run git -C source args; return stdout bytes, or raise Refused on non-zero exit."""
    r = run(["git", "-C", str(source), *args])
    if r.returncode != 0:
        err = r.stderr.decode("utf-8", "replace").strip() if isinstance(r.stderr, bytes) else str(r.stderr or "").strip()
        raise Refused(f"git {' '.join(args)} failed: {err}")
    return r.stdout if isinstance(r.stdout, bytes) else r.stdout.encode("utf-8")


def check_origin(run: Callable[[Sequence[str]], Any], source: Path | str) -> str:
    """Refuse a repository whose origin remote is not senseiewok/cf-research."""
    out = git(run, source, "remote", "get-url", "origin").decode("utf-8", "replace").strip()
    if out not in ALLOWED_ORIGINS:
        raise Refused(f"{source}: origin is {out!r}, not senseiewok/cf-research")
    return out


def resolve_commit(
    run: Callable[[Sequence[str]], Any],
    source: Path | str,
    ref: str,
    allow_old: bool = False,
) -> str:
    """Resolve ref to a 40-char SHA and verify it is an ancestor of origin/main (unless allow_old)."""
    if not isinstance(ref, str) or not ref or ref.startswith("-"):
        raise Refused(f"--ref {ref!r}: must be a commit or branch, not an option")
    raw = git(run, source, "rev-parse", "--verify", "--end-of-options", f"{ref}^{{commit}}")
    commit = raw.decode("ascii", "replace").strip()
    if not COMMIT_RE.match(commit):
        raise Refused(f"git gave {commit!r} for {ref!r}, not a full commit id")
    if not allow_old:
        r = run(["git", "-C", str(source), "merge-base", "--is-ancestor", commit, "origin/main"])
        if r.returncode != 0:
            raise Refused(
                f"{commit} is not an ancestor of origin/main in {source}: pin only a commit on origin/main "
                "(or pass --allow-old)"
            )
    return commit


def commit_date(run: Callable[[Sequence[str]], Any], source: Path | str, commit: str) -> str:
    """The commit date as YYYY-MM-DD (git's %cs)."""
    raw = git(run, source, "show", "-s", "--format=%cs", commit)
    val = raw.decode("ascii", "replace").strip()
    if not DATE_RE.match(val):
        raise Refused(f"git gave {val!r} as the date of {commit}")
    return val


def commits_behind(
    run: Callable[[Sequence[str]], Any],
    source: Path | str,
    commit: str,
) -> tuple[int, int]:
    """Return (total_commits_behind, catalog_commits_behind) relative to origin/main."""
    raw_tip = git(run, source, "rev-parse", "--verify", "origin/main^{commit}")
    tip = raw_tip.decode("ascii", "replace").strip()
    if tip == commit:
        return 0, 0
    raw_total = git(run, source, "rev-list", "--count", f"{commit}..origin/main")
    total = int(raw_total.decode("ascii", "replace").strip())
    raw_cat = git(run, source, "rev-list", "--count", f"{commit}..origin/main", "--", CATALOG_RESEARCH_PATH)
    cat = int(raw_cat.decode("ascii", "replace").strip())
    return total, cat


def show_catalog(run: Callable[[Sequence[str]], Any], source: Path | str, commit: str) -> bytes:
    """Show the catalog content at the given commit."""
    return git(run, source, "show", f"{commit}:{CATALOG_RESEARCH_PATH}")


def build_copy(raw_bytes: bytes) -> tuple[bytes, str, str, int]:
    """Format raw catalog bytes into generated copy, returning (copy_bytes, raw_sha, copy_sha, count)."""
    norm_raw = raw_bytes.replace(b"\r\n", b"\n")
    raw_sha = hashlib.sha256(norm_raw).hexdigest()
    try:
        text = norm_raw.decode("utf-8")
    except UnicodeDecodeError as exc:
        raise Refused(f"source catalog is not valid UTF-8: {exc}") from exc
    body = strip_header(text)
    count = count_sources(body)
    copy_text = HEADER + "\n" + body
    copy_bytes = copy_text.encode("utf-8")
    copy_sha = hashlib.sha256(copy_bytes).hexdigest()
    return copy_bytes, raw_sha, copy_sha, count


def pin(
    source: Path | str,
    ref: str = "origin/main",
    date: str | None = None,
    allow_old: bool = False,
    run: Callable[[Sequence[str]], Any] = default_run,
    target_catalog: Path = CATALOG_PATH,
    target_lock: Path = LOCK_PATH,
    check_remote_origin: bool = True,
) -> dict[str, Any]:
    """Pin the catalog copy and write catalog.yaml and catalog.lock.json."""
    if check_remote_origin:
        check_origin(run, source)
    commit = resolve_commit(run, source, ref, allow_old=allow_old)
    c_date = commit_date(run, source, commit)
    pinned_on = date or datetime.date.today().isoformat()
    if not DATE_RE.match(pinned_on):
        raise Refused(f"invalid date {pinned_on!r}")

    raw_bytes = show_catalog(run, source, commit)
    copy_bytes, raw_sha, copy_sha, count = build_copy(raw_bytes)

    lock_data = {
        "schema_version": SCHEMA_VERSION,
        "research_commit": commit,
        "commit_date": c_date,
        "pinned_on": pinned_on,
        "inputs": {
            CATALOG_RESEARCH_PATH: raw_sha,
        },
        "copy_sha256": copy_sha,
        "sources": count,
    }

    target_catalog.parent.mkdir(parents=True, exist_ok=True)
    target_catalog.write_bytes(copy_bytes)
    target_lock.write_text(json.dumps(lock_data, indent=2, sort_keys=True) + "\n", encoding="utf-8")
    return lock_data


def status(
    source: Path | str = DEFAULT_SOURCE,
    lock_file: Path = LOCK_PATH,
    run: Callable[[Sequence[str]], Any] = default_run,
) -> int:
    """Report how far behind the pinned commit is relative to origin/main."""
    if not lock_file.is_file():
        print(f"error: lock file {lock_file} is missing; run pin first")
        return 2
    try:
        lock = json.loads(lock_file.read_text(encoding="utf-8"))
    except Exception as exc:
        print(f"error: invalid lock file {lock_file}: {exc}")
        return 2

    commit = lock.get("research_commit", "")
    c_date = lock.get("commit_date", "")
    sources = lock.get("sources", 0)
    short_commit = commit[:7] if commit else "unknown"

    source_path = Path(source)
    if not (source_path / ".git").exists() and not (source_path / "HEAD").exists():
        print(f"pinned to commit {short_commit} ({c_date}); research repository not found at {source}")
        return 0

    try:
        total_behind, cat_behind = commits_behind(run, source_path, commit)
    except Refused as exc:
        print(f"error: could not check status against {source}: {exc}")
        return 2

    if total_behind == 0:
        print(f"pinned to commit {short_commit} ({c_date}); in sync with origin/main (0 commits behind, {sources} sources)")
    else:
        print(
            f"pinned to commit {short_commit} ({c_date}); origin/main is {total_behind} commit(s) ahead "
            f"({cat_behind} touching {CATALOG_RESEARCH_PATH})"
        )
    return 0


def check(
    source: Path | str = DEFAULT_SOURCE,
    catalog_file: Path = CATALOG_PATH,
    lock_file: Path = LOCK_PATH,
    run: Callable[[Sequence[str]], Any] = default_run,
) -> int:
    """Verify catalog.yaml matches PINNED commit and catalog.lock.json."""
    if not lock_file.is_file():
        print(f"DRIFT: lock file {lock_file} is missing")
        return 1
    if not catalog_file.is_file():
        print(f"DRIFT: catalog copy {catalog_file} is missing")
        return 1

    try:
        lock = json.loads(lock_file.read_text(encoding="utf-8"))
    except Exception as exc:
        print(f"DRIFT: invalid lock file: {exc}")
        return 1

    commit = lock.get("research_commit", "")
    expected_copy_sha = lock.get("copy_sha256", "")
    expected_raw_sha = lock.get("inputs", {}).get(CATALOG_RESEARCH_PATH, "")
    c_date = lock.get("commit_date", "")
    short_commit = commit[:7] if commit else "unknown"

    try:
        current_copy_bytes = catalog_file.read_bytes()
    except Exception as exc:
        print(f"DRIFT: cannot read {catalog_file}: {exc}")
        return 1

    current_copy_sha = lf_sha256(current_copy_bytes)
    if current_copy_sha != expected_copy_sha:
        print(f"DRIFT: catalog copy {catalog_file} has been modified (sha256 mismatch with lock)")
        return 1

    source_path = Path(source)
    is_git_source = (source_path / ".git").exists() or (source_path / "HEAD").exists()

    if is_git_source:
        try:
            raw_bytes = show_catalog(run, source_path, commit)
        except Refused as exc:
            print(f"DRIFT: could not read pinned commit {short_commit} in {source}: {exc}")
            return 1

        norm_raw_sha = lf_sha256(raw_bytes)
        if norm_raw_sha != expected_raw_sha:
            print(f"DRIFT: raw catalog at pinned commit {short_commit} differs from recorded hash")
            return 1

        try:
            expected_bytes, _, _, _ = build_copy(raw_bytes)
        except Refused as exc:
            print(f"DRIFT: failed formatting pinned catalog: {exc}")
            return 1

        if current_copy_bytes.replace(b"\r\n", b"\n") != expected_bytes.replace(b"\r\n", b"\n"):
            print(f"DRIFT: catalog copy differs from pinned research commit {short_commit}")
            return 1

        print(f"in sync with pinned research commit {short_commit} ({c_date})")
        return 0
    else:
        print(f"in sync (standalone: matches catalog.lock.json hash for commit {short_commit})")
        return 0


def main(argv: Sequence[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--source", type=Path, default=DEFAULT_SOURCE, help="Path to cf-research repository")
    parser.add_argument("--ref", default="origin/main", help="Research commit or branch to pin to")
    parser.add_argument("--date", help="Pin date as YYYY-MM-DD")
    parser.add_argument("--allow-old", action="store_true", help="Allow pinning an older commit not on origin/main")
    parser.add_argument("--status", action="store_true", help="Report commits behind origin/main")
    parser.add_argument("--check", action="store_true", help="Verify copy against pinned commit and lock")
    parser.add_argument("--verify", action="store_true", help="Alias for --check")
    args = parser.parse_args(argv)

    if args.status:
        return status(source=args.source)
    if args.check or args.verify:
        return check(source=args.source)

    try:
        data = pin(
            source=args.source,
            ref=args.ref,
            date=args.date,
            allow_old=args.allow_old,
        )
    except Refused as exc:
        print(f"error: {exc}")
        return 2

    short_commit = data["research_commit"][:7]
    print(f"pinned to commit {short_commit} ({data['commit_date']}); {data['sources']} sources")
    return 0


if __name__ == "__main__":
    sys.exit(main())
